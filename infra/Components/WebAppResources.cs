using Blog.Infra.Common;
using Pulumi;
using Pulumi.AzureNative.ApplicationInsights;
using Pulumi.AzureNative.Web;
using Pulumi.AzureNative.Web.Inputs;

namespace Blog.Infra.Components;

internal sealed class WebAppResources
{
    private const string Name = "codechef";

    public static readonly IReadOnlyList<string> CustomDomains = ["shahabganji.dev", "shahab-the-guy.dev"];

    public WebAppResources(StackSettings settings, Output<string> resourceGroupName, Component appInsights)
    {
        var siteId = $"{settings.ResourceGroupId}/providers/Microsoft.Web/sites/{Name}";

        Plan = new AppServicePlan(Name, new AppServicePlanArgs
        {
            ResourceGroupName = resourceGroupName,
            Name = Name,
            Location = settings.Location,
            Kind = "linux",
            Reserved = true,
            PerSiteScaling = false,
            ZoneRedundant = false,
            ElasticScaleEnabled = false,
            MaximumElasticWorkerCount = 1,
            IsSpot = false,
            HyperV = false,
            IsXenon = false,
            Sku = new SkuDescriptionArgs
            {
                Name = "B1",
                Tier = "Basic",
                Size = "B1",
                Family = "B",
                Capacity = 1,
            },
            Tags = Tags.Default,
        }, BlogResourceOptions.For(
            settings,
            $"{settings.ResourceGroupId}/providers/Microsoft.Web/serverfarms/{Name}",
            // Platform-managed values reported by Azure; ignoring keeps their current values on updates.
            ignoreChanges: ["freeOfferExpirationTime", "targetWorkerCount", "targetWorkerSizeId", "asyncScalingEnabled", "isCustomMode"]));

        Site = new WebApp(Name, new WebAppArgs
        {
            ResourceGroupName = resourceGroupName,
            Name = Name,
            Location = settings.Location,
            Kind = "app,linux",
            ServerFarmId = Plan.Id,
            Reserved = true,
            HttpsOnly = true,
            ClientAffinityEnabled = true,
            Enabled = true,
            ClientAffinityProxyEnabled = false,
            ClientCertEnabled = false,
            ClientCertMode = ClientCertMode.Required,
            EndToEndEncryptionEnabled = false,
            HostNamesDisabled = false,
            SshEnabled = true,
            StorageAccountRequired = false,
            IpMode = IPMode.IPv4,
            RedundancyMode = RedundancyMode.None,
            ContainerSize = 0,
            DailyMemoryTimeQuota = 0,
            PublicNetworkAccess = "Enabled",
            OutboundVnetRouting = new OutboundVnetRoutingArgs
            {
                AllTraffic = false,
                ApplicationTraffic = false,
                BackupRestoreTraffic = false,
                ContentShareTraffic = false,
                ImagePullTraffic = false,
            },
            KeyVaultReferenceIdentity = "SystemAssigned",
            AutoGeneratedDomainNameLabelScope = AutoGeneratedDomainNameLabelScope.TenantReuse,
            SiteConfig = new SiteConfigArgs
            {
                LinuxFxVersion = "dotnet|11",
                AppCommandLine = "",
                AlwaysOn = true,
                AutoHealEnabled = false,
                AcrUseManagedIdentityCreds = false,
                PublicNetworkAccess = "Enabled",
                ScmType = ScmType.None,
                PreWarmedInstanceCount = 0,
                MinimumElasticInstanceCount = 1,
                ElasticWebAppScaleLimit = 0,
                FunctionsRuntimeScaleMonitoringEnabled = false,
                Http20ProxyFlag = 0,
                LogsDirectorySizeLimit = 35,
                IpSecurityRestrictions = { AllowAll() },
                ScmIpSecurityRestrictions = { AllowAll() },
                ScmIpSecurityRestrictionsUseMain = false,
                DefaultDocuments =
                {
                    "Default.htm", "Default.html", "Default.asp", "index.htm", "index.html",
                    "iisstart.htm", "default.aspx", "index.php", "hostingstart.html",
                },
                VirtualApplications =
                {
                    new VirtualApplicationArgs { VirtualPath = "/", PhysicalPath = "site\\wwwroot", PreloadEnabled = true },
                },
                Http20Enabled = false,
                MinTlsVersion = SupportedTlsVersions.SupportedTlsVersions_1_2,
                ScmMinTlsVersion = SupportedTlsVersions.SupportedTlsVersions_1_2,
                FtpsState = FtpsState.FtpsOnly,
                WebSocketsEnabled = false,
                Use32BitWorkerProcess = true,
                NumberOfWorkers = 1,
                LoadBalancing = SiteLoadBalancing.LeastRequests,
                ManagedPipelineMode = ManagedPipelineMode.Integrated,
                RemoteDebuggingEnabled = false,
                DetailedErrorLoggingEnabled = false,
                HttpLoggingEnabled = false,
                RequestTracingEnabled = false,
                VnetRouteAllEnabled = false,
            },
            Tags =
            {
                // Created by the portal when App Insights was attached; links the site to its component.
                { "hidden-link: /app-insights-resource-id", appInsights.Id },
            },
        }, BlogResourceOptions.For(
            settings,
            siteId,
            ignoreChanges:
            [
                // Computed by Azure.
                "customDomainVerificationId",
                // Custom domains/TLS are managed by the WebAppHostNameBinding resources and Azure managed certificates.
                "hostNameSslStates",
                // Settings of other (Windows / non .NET) stacks and VNet integration that do not apply to this site.
                "siteConfig.netFrameworkVersion",
                "siteConfig.nodeVersion",
                "siteConfig.phpVersion",
                "siteConfig.pythonVersion",
                "siteConfig.powerShellVersion",
                "siteConfig.vnetName",
                "siteConfig.vnetPrivatePortsCount",
            ]));

        AppSettings = new WebAppApplicationSettings("codechef-app-settings", new WebAppApplicationSettingsArgs
        {
            ResourceGroupName = resourceGroupName,
            Name = Site.Name,
            Properties =
            {
                { "APPLICATIONINSIGHTS_CONNECTION_STRING", appInsights.ConnectionString },
                { "ApplicationInsightsAgent_EXTENSION_VERSION", "~3" },
                { "XDT_MicrosoftApplicationInsights_Mode", "Recommended" },
            },
        }, BlogResourceOptions.For(settings, $"{siteId}/config/appsettings"));

        foreach (var domain in CustomDomains)
        {
            HostNameBindings.Add(new WebAppHostNameBinding($"codechef-host-{domain}", new WebAppHostNameBindingArgs
            {
                ResourceGroupName = resourceGroupName,
                Name = Site.Name,
                HostName = domain,
                SiteName = Name,
                HostNameType = HostNameType.Verified,
            }, BlogResourceOptions.For(
                settings,
                $"{siteId}/hostNameBindings/{domain}",
                // TLS uses App Service managed certificates which Azure renews (new thumbprint) on its own.
                ignoreChanges: ["sslState", "thumbprint"])));
        }

        ScmBasicAuth = new WebAppScmAllowed("codechef-scm-basic-auth", new WebAppScmAllowedArgs
        {
            ResourceGroupName = resourceGroupName,
            Name = Site.Name,
            Allow = false,
        }, BlogResourceOptions.For(settings, $"{siteId}/basicPublishingCredentialsPolicies/scm"));

        FtpBasicAuth = new WebAppFtpAllowed("codechef-ftp-basic-auth", new WebAppFtpAllowedArgs
        {
            ResourceGroupName = resourceGroupName,
            Name = Site.Name,
            Allow = false,
        }, BlogResourceOptions.For(settings, $"{siteId}/basicPublishingCredentialsPolicies/ftp"));
    }

    public AppServicePlan Plan { get; }

    private static IpSecurityRestrictionArgs AllowAll() => new()
    {
        Name = "Allow all",
        Description = "Allow all access",
        Action = "Allow",
        IpAddress = "Any",
        Priority = int.MaxValue,
    };

    public WebApp Site { get; }

    public WebAppApplicationSettings AppSettings { get; }

    public List<WebAppHostNameBinding> HostNameBindings { get; } = [];

    public WebAppScmAllowed ScmBasicAuth { get; }

    public WebAppFtpAllowed FtpBasicAuth { get; }
}
